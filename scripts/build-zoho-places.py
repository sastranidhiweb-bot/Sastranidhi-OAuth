"""Map the registration form's country and state names to Zoho CRM's.

The launch registration form posts to a Zoho CRM Web-to-Lead form whose
Country and State fields are picklists. Zoho spells many places differently
from our GeoNames lists (e.g. "Czechia" vs "Czech Republic", "Punjab" vs
"Punjab (India)"), so this builds a lookup from our names to theirs.

Source: the form's dependency script, which holds Zoho's picklists.

Usage:
    python scripts/build-zoho-places.py

Run again after scripts/build-geo-data.py, or if the CRM team changes the
form. Writes src/data/zohoPlaces.js with only the names that differ; a
name not listed there is sent to Zoho as it is.
"""

import json
import re
import sys
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# WebFormDependencies script of the "Register for the launch" form
# (form id 1449582000000732001); see LaunchRegistrationPage.jsx.
DEPS_URL = (
    'https://crm.zohopublic.in/crm/WebFormDependencies'
    '?rid=081bd54867b4cb267bb41722c3d85de80071d72ef74b6481b6796c5a48379ce2'
)

# Countries Zoho names too differently to match automatically, by ISO code.
COUNTRY_FIXES = {
    'BL': 'Saint-Barthelemy',
    'BQ': 'Bonaire, Sint Eustatius and Saba',
    'CC': 'Cocos (Keeling) Islands',
    'CI': "Cote D'Ivoire (Ivory Coast)",
    'CV': 'Cape Verde',
    'CZ': 'Czech Republic',
    'FJ': 'Fiji Islands',
    'GG': 'Guernsey and Alderney',
    'HK': 'Hong Kong S.A.R.',
    'MF': 'Saint-Martin (French part)',
    'MO': 'Macau S.A.R.',
    'NL': 'Netherlands',
    'PN': 'Pitcairn Island',
    'PS': 'Palestine',
    'SH': 'Saint Helena, Ascension and Tristan da Cunha',
    'SJ': 'Svalbard and Jan Mayen Islands',
    'SX': 'Sint Maarten (Dutch part)',
    'TL': 'Timor-Leste',
    'TR': 'Türkiye',
    'VA': 'Vatican City State (Holy See)',
    'VG': 'Virgin Islands (British)',
    'WF': 'Wallis and Futuna Islands',
}

# Words that one list adds and the other leaves out ("Kayes" / "Kayes Region")
FILLER = re.compile(
    r'\b(province|region|state|governorate|district|county|department|'
    r'prefecture|oblast|voivodeship|municipality|of|the)\b'
)


def plain(name):
    """Lower case, without diacritics."""
    decomposed = unicodedata.normalize('NFD', name)
    return ''.join(ch for ch in decomposed if not unicodedata.combining(ch)).lower()


def loose(name):
    """plain() without "(Country)" qualifiers, filler words and punctuation."""
    name = re.sub(r'\s*\(.*?\)', '', plain(name))
    return re.sub(r'[^a-z]', '', FILLER.sub('', name))


def matcher(zoho_names):
    """Finds the Zoho name for one of ours: exact, then plain(), then loose().
    A looser key shared by two Zoho names is ambiguous and not used."""
    tables = []
    for key in (plain, loose):
        table = {}
        for z in zoho_names:
            table.setdefault(key(z), []).append(z)
        tables.append((key, table))

    def find(name):
        if name in zoho_names:
            return name
        for key, table in tables:
            hits = table.get(key(name), [])
            if len(hits) == 1:
                return hits[0]
        return None

    return find


def main():
    script = urllib.request.urlopen(DEPS_URL, timeout=30).read().decode('utf-8')
    data = json.loads(re.search(r'var mapObj\d+ = (\{.*?\});var mapFldObj', script, re.S).group(1))
    zoho_states = {c: [s for s in v if s != '-None-'] for c, v in data['countryVsStates'].items()}
    find_country = matcher([c for c in data['countries'] if c != '-None-'])

    countries_js = (ROOT / 'src' / 'data' / 'countries.js').read_text(encoding='utf-8')
    ours = re.findall(r"code: '(\w+)', name: \"(.*?)\"", countries_js)

    country_map, state_map = {}, {}
    no_country, unmatched, total = [], 0, 0
    for code, name in ours:
        zoho = COUNTRY_FIXES.get(code) or find_country(name)
        if zoho and zoho not in data['countries']:
            sys.exit(f'COUNTRY_FIXES[{code!r}] = {zoho!r} is not in the Zoho form')
        if not zoho:
            no_country.append(f'{code} {name}')
            continue
        if zoho != name:
            country_map[code] = zoho

        places = ROOT / 'public' / 'data' / 'places' / f'{code}.json'
        if not places.exists():
            continue
        find_state = matcher(zoho_states.get(zoho, []))
        for state in json.loads(places.read_text(encoding='utf-8'))['states']:
            total += 1
            z = find_state(state)
            if z is None:
                unmatched += 1
            elif z != state:
                state_map.setdefault(code, {})[state] = z

    out = ROOT / 'src' / 'data' / 'zohoPlaces.js'
    out.write_text(
        '// Generated by scripts/build-zoho-places.py from the Zoho CRM form. Do not edit.\n'
        '// Our country (by ISO code) and state names -> Zoho CRM picklist values,\n'
        '// listing only those that differ.\n'
        f'export const zohoCountries = {json.dumps(country_map, ensure_ascii=False, indent=2)};\n\n'
        f'export const zohoStates = {json.dumps(state_map, ensure_ascii=False, indent=2)};\n',
        encoding='utf-8',
    )
    print(f'{len(country_map)} countries and {sum(len(v) for v in state_map.values())} states renamed')
    print(f'not in Zoho: {len(no_country)} countries ({", ".join(no_country)}), '
          f'{unmatched} of {total} states')


if __name__ == '__main__':
    main()
